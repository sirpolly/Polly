# Определяем целевое слово (в нижнем регистре)
target_word = "карамба"

# Инициализируем счетчик совпадений
count = 0

# Запрашиваем у пользователя ввод десяти слов
for i in range(10):
    word = input(f"Введите слово {i + 1}: ").strip()  # Убираем лишние пробелы

    # Проверяем совпадение, игнорируя регистр
    if word.lower() == target_word:
        count += 1

# Выводим результат
print(f"Количество слов, совпадающих со словом 'Карамба': {count}\n")

# Дополнительная демонстрация работы со строками
print("Все введенные слова: ", end="")
for i in range(10):
    word = input(f"Введите слово {i + 1}: ").strip()
    print(word, end=", ")  # Выводим слова через запятую

print("\n")  # Переводим на новую строку после вывода всех слов
