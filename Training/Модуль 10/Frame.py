# Запросить у пользователя ширину и высоту рамки
width = int(input("Введите ширину рамки: "))
height = int(input("Введите высоту рамки: "))

# Рисуем верхнюю границу рамки
print("-" * width)

# Рисуем боковые границы
for _ in range(height - 2):  # Учитываем верхнюю и нижнюю границы
    print("|" + " " * (width - 2) + "|")

# Рисуем нижнюю границу рамки
print("-" * width)
